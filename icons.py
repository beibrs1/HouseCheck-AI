_cache: dict[tuple, QPixmap] = {}


def pixmap(name: str, color: str, size: int = 20, stroke: float = 2.0, dpr: float = 2.0) -> QPixmap:
    key = (name, color, size, stroke, dpr)
    if key in _cache:
        return _cache[key]
    body = _P.get(name, _P["sparkle"]).replace("currentColor", color)
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
        f'stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>'
    )
    renderer = QSvgRenderer(QByteArray(svg.encode("utf-8")))
    px = QPixmap(int(size * dpr), int(size * dpr))
    px.fill(Qt.transparent)
    painter = QPainter(px)
    painter.setRenderHint(QPainter.Antialiasing)
    renderer.render(painter, QRectF(0, 0, size * dpr, size * dpr))
    painter.end()
    px.setDevicePixelRatio(dpr)
    _cache[key] = px
    return px


def icon(name: str, color: str, size: int = 20) -> QIcon:
    return QIcon(pixmap(name, color, size))


def paint(painter: QPainter, name: str, color: str, rect: QRectF, stroke: float = 2.0) -> None:
    size = int(max(rect.width(), rect.height()))
    painter.drawPixmap(rect.toRect(), pixmap(name, color, size, stroke))
